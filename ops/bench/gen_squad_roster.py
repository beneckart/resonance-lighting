#!/usr/bin/env python3
"""Generate the firmware's lantern roster from the Tone Lab tone map.

The Tone Lab (decompression_tone_lab.py) is the source of truth for which
lanterns are in the squad, their pitch order and each one's tuned strike pulse.
This writes firmware/fixture/src/core/squad_roster.h, used by the perimeter
squad trigger (pulses + rising-pitch steps), the lanterns' local signature
(each lantern finds its own pulse) and the Atom (ids). Re-run after retuning:

  python3 ops/bench/gen_squad_roster.py --site "Brian bench"
"""
import argparse, csv, json, pathlib

REPO = pathlib.Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument("--site", default="Brian bench")
ap.add_argument("--out", default=str(REPO / "firmware/fixture/src/core/squad_roster.h"))
a = ap.parse_args()
state = json.load(open(REPO / "ops/bench/data" / a.site / "decompression-tone-map.json"))
callsigns = {r["fixture_id"]: r["callsign"] for r in csv.DictReader(open(REPO / "ops/fleet/callsigns.csv"))}
default = int(state.get("pulse_ms") or 40)
rows = []
triggers = []  # Tone Lab meta cycle_trigger: the lantern whose sensor advances the cycle
for fid in state["order"]:  # tone order: 1 = highest pitch
    meta = state["lanterns"].get(fid, {})
    if meta.get("role") == "perimeter":
        continue  # perimeter lights have no chime
    pulse = int(meta.get("pulse_ms") or default)
    if not 5 <= pulse <= 100:
        raise SystemExit(f"{fid}: pulse {pulse} ms out of the roster range 5..100")
    name = meta.get("callsign") or callsigns.get(fid) or fid
    rows.append((name, fid, pulse, meta.get("partner")))
    if meta.get("cycle_trigger"):
        triggers.append(fid)
if not 1 <= len(rows) <= 15:
    raise SystemExit(f"roster needs 1..15 lanterns, got {len(rows)}")
lines = [
    "#pragma once",
    "// GENERATED by ops/bench/gen_squad_roster.py from the Tone Lab tone map",
    f"// (ops/bench/data/{a.site}/decompression-tone-map.json, updated {state.get('updated_utc')}).",
    "// Do not edit by hand: retune in the Tone Lab and re-run the generator.",
    "// Order is the tone order, highest pitch first; pulseMs is each lantern's tuned strike.",
    "",
    "static constexpr SquadMember SQUAD[] = {",
]
ids = [r[1] for r in rows]
for name, fid, pulse, partner in rows:
    pi = ids.index(partner) if partner in ids else -1  # lantern-dings partner (Tone Lab meta "partner")
    if partner and pi < 0:
        raise SystemExit(f"{fid}: partner {partner} is not a lantern in the roster")
    lines.append(f'  {{"{name}",{" " * max(0, 8 - len(name))}{{0x{fid[0:2]},0x{fid[2:4]},0x{fid[4:6]}}},{pulse},{pi}}},')
if len(triggers) > 1:
    raise SystemExit(f"only one cycle trigger lantern allowed, got {triggers}")
lines += ["};", "",
          "// Lantern whose downward sensor advances the event cycle (Tone Lab \"Cycle trigger\"),",
          "// as a roster index; -1 = none (only a perimeter can trigger the cycle).",
          f"static constexpr int SQUAD_TRIGGER_LANTERN = {ids.index(triggers[0]) if triggers else -1};", ""]
# Freakout Mode, played by the trigger lantern on a four-perimeter hold or an
# Atom press (no laptop/T-Deck needed): steps at its BPM, roster bitmask per step.
fo = next((p for p in state.get("patterns", {}).values() if p.get("name") == "Freakout Mode"), None)
if not fo:
    raise SystemExit("tone map has no pattern named 'Freakout Mode'")
steps, spb, bpm = int(fo["steps"]), int(fo["steps_per_beat"]), float(fo["bpm"])
masks = [0] * steps
for fid, idx in (fo.get("hits") or {}).items():
    if fid.upper() in ids:
        for i in idx:
            if 0 <= int(i) < steps:
                masks[int(i)] |= 1 << ids.index(fid.upper())
step_ms = 60000.0 / (bpm * spb)
lines += ["// Freakout Mode (Tone Lab pattern): roster bitmask per step, played on a",
          "// four-perimeter hold or an Atom press by the trigger lantern.",
          f"static constexpr uint16_t SQUAD_FREAKOUT_STEP_MS = {round(step_ms)};",
          f"static constexpr uint8_t SQUAD_FREAKOUT_STEPS = {steps};",
          "static constexpr uint16_t SQUAD_FREAKOUT[] = {" + ",".join(f"0x{m:03x}" for m in masks) + "};", ""]
pathlib.Path(a.out).write_text("\n".join(lines))
print(f"wrote {a.out}: " + ", ".join(f"{n} {p} ms" + (f" -> partner {next(r[0] for r in rows if r[1] == q)}" if q in ids else "") for n, _, p, q in rows))
